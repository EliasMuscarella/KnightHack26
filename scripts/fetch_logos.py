"""Find, download, sanitize and register genuine company logos (dev-time only).

Usage:
    uv run python scripts/fetch_logos.py [--dry-run] [--tickers NVDA,MSFT] [--force]

For every company in the report library (GET http://localhost:8000/companies, or the
`company` block of data/published/*.json when the API is down) this script:

1. finds the Wikidata item whose "Central Index Key" (P5531) equals the company's SEC CIK
   (10-digit zero-padded form first, then the unpadded form), never by name;
2. takes "small logo or icon" (P8972) when present, else "logo image" (P154), skipping
   values with an end date (former logos) and deprecated ones, preferring the preferred rank;
3. resolves the Commons file (imageinfo), keeps only image/svg+xml files of at most 400 KB,
   and records the license;
4. sanitizes the SVG with an element/attribute allowlist (fail closed) and writes it to
   web/public/logos/{TICKER}.svg, the manifest block in web/src/lib/logos.ts and the table in
   web/public/logos/SOURCES.md.

The web app never fetches a logo at runtime; this script is the only thing that touches the
network, and only the hosts in ALLOWED_ORIGINS. Responses and downloads are cached under
data/cache/logos/ so a re-run without --force makes no network calls for what it already has.
Exit code 0 even when some companies get no logo; 1 only on a script error.
"""

