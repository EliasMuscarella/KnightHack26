def check_url(url: str) -> str:
    """Raise DisallowedURLError unless the URL's scheme and host are on the allowlist."""
    parts = urlsplit(url)
    if parts.username or parts.password:
        raise DisallowedURLError(f"credentials in URL are not allowed: {url}")
    origin = (parts.scheme.lower(), parts.netloc.lower())
    if origin not in ALLOWED_ORIGINS:
        raise DisallowedURLError(f"host not on the allowlist: {parts.scheme}://{parts.netloc}")
    return url


class PoliteClient:
    """One request at a time, about 1/s, allowlisted hosts only, manual redirect validation,
    backoff on 429/503 and on Wikimedia `maxlag` errors, and an on-disk cache."""

    def __init__(
        self,
        *,
        cache_dir: Path | None = CACHE_DIR,
        use_cache: bool = True,
        write_cache: bool = True,
        min_interval: float = MIN_INTERVAL_S,
        sleep=time.sleep,
        transport: httpx.BaseTransport | None = None,
    ) -> None:
        self._client = httpx.Client(
            headers={"User-Agent": USER_AGENT},
            follow_redirects=False,
            timeout=httpx.Timeout(30.0),
            transport=transport,
        )
        self._cache_dir = cache_dir
        self._use_cache = use_cache and cache_dir is not None
        self._write_cache = write_cache and cache_dir is not None
        self._min_interval = min_interval
        self._sleep = sleep
        self._last = 0.0
        self.network_calls = 0

    def close(self) -> None:
        self._client.close()

    # cache ------------------------------------------------------------------------------
    def _cache_path(self, url: str, kind: str) -> Path | None:
        if self._cache_dir is None:
            return None
        digest = hashlib.sha256(url.encode("utf-8")).hexdigest()
        return self._cache_dir / kind / digest

    def _cache_read(self, url: str, kind: str) -> bytes | None:
        path = self._cache_path(url, kind)
        if self._use_cache and path is not None and path.is_file():
            return path.read_bytes()
        return None

    def _cache_write(self, url: str, kind: str, body: bytes) -> None:
        path = self._cache_path(url, kind)
        if self._write_cache and path is not None:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(body)

    # network ----------------------------------------------------------------------------
    def _pace(self) -> None:
        wait = self._last + self._min_interval - time.monotonic()
        if wait > 0:
            self._sleep(wait)
        self._last = time.monotonic()

    def _send(self, url: str) -> httpx.Response:
        """GET with each redirect hop validated against the allowlist."""
        current = check_url(url)
        for _ in range(MAX_REDIRECTS + 1):
            self._pace()
            self.network_calls += 1
            resp = self._client.get(current)
            if resp.is_redirect:
                location = resp.headers.get("location", "")
                current = check_url(urljoin(current, location))
                continue
            return resp
        raise FetchError(f"too many redirects for {url}")

    def get_bytes(self, url: str, *, kind: str, max_bytes: int | None = None) -> bytes:
        cached = self._cache_read(url, kind)
        if cached is not None:
            return cached
        delay = 5.0
        for attempt in range(1, MAX_ATTEMPTS + 1):
            try:
                resp = self._send(url)
            except httpx.HTTPError as exc:
                raise FetchError(f"{type(exc).__name__} for {urlsplit(url).netloc}") from exc
            retry_after = _retry_after(resp)
            if resp.status_code in (429, 503):
                if attempt == MAX_ATTEMPTS:
                    raise FetchError(f"HTTP {resp.status_code} after {attempt} attempts")
                self._sleep(retry_after if retry_after is not None else delay)
                delay = min(delay * 2, 60.0)
                continue
            if resp.status_code != 200:
                raise FetchError(f"HTTP {resp.status_code} from {urlsplit(url).netloc}")
            body = resp.content
            if max_bytes is not None and len(body) > max_bytes:
                raise FetchError(f"response larger than {max_bytes} bytes")
            if kind == "api":
                payload = _json_or_error(body)
                if _is_maxlag(payload):
                    if attempt == MAX_ATTEMPTS:
                        raise FetchError(f"Wikimedia maxlag after {attempt} attempts")
                    self._sleep(retry_after if retry_after is not None else delay)
                    delay = min(delay * 2, 60.0)
                    continue
                if isinstance(payload, dict) and "error" in payload:
                    code = payload["error"].get("code", "unknown") if isinstance(payload["error"], dict) else "unknown"
                    raise FetchError(f"API error: {code}")
            self._cache_write(url, kind, body)
            return body
        raise FetchError("retries exhausted")  # pragma: no cover

    def get_api(self, base: str, params: dict[str, str]) -> dict:
        query = dict(params)
        query.update({"format": "json", "formatversion": "2", "maxlag": "5"})
        url = f"{base}?{urlencode(sorted(query.items()))}"
        payload = _json_or_error(self.get_bytes(url, kind="api"))
        if not isinstance(payload, dict):
            raise FetchError("unexpected API response")
        return payload

    def get_live_json(self, url: str) -> object:
        """Uncached JSON GET (the local company list changes as reports are published)."""
        resp = self._send(url)
        if resp.status_code != 200:
            raise FetchError(f"HTTP {resp.status_code}")
        return _json_or_error(resp.content)


def _retry_after(resp: httpx.Response) -> float | None:
    value = resp.headers.get("retry-after", "")
    try:
        return min(max(float(value), 1.0), 60.0)
    except ValueError:
        return None


def _json_or_error(body: bytes) -> object:
    try:
        return json.loads(body)
    except ValueError as exc:
        raise FetchError("response is not JSON") from exc


def _is_maxlag(payload: object) -> bool:
    return (
        isinstance(payload, dict)
        and isinstance(payload.get("error"), dict)
        and payload["error"].get("code") == "maxlag"
    )


