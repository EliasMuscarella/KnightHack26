@dataclass
class Outcome:
    ticker: str
    status: str  # found | swapped | kept | skipped
    detail: str = ""
    prop: str = ""
    shape: str = ""
    file_name: str = ""
    license: str = ""
    svg: str = ""
    row: SourceRow | None = None
    notes: list[str] = field(default_factory=list)


def process_company(
    client: PoliteClient, company: Company, manifest: dict[str, str], *, force: bool
) -> Outcome:
    ticker = company.ticker
    # A hand-added raster logo (RASTER_LOGOS in logos.ts) exists because Commons has no SVG; the
    # script never replaces it, even with --force (remove the PNG by hand to switch to an SVG).
    if (LOGO_DIR / f"{ticker}.png").is_file() and ticker in manifest:
        return Outcome(ticker, "kept", "hand-added PNG logo", shape=manifest[ticker])
    have = (LOGO_DIR / f"{ticker}.svg").is_file() and ticker in manifest
    existing_shape = manifest.get(ticker)
    if have and not force and existing_shape == "mark":
        return Outcome(ticker, "kept", "existing square mark (use --force to replace)", shape="mark")

    qids = find_qids(client, company.cik)
    if not qids:
        return Outcome(ticker, "skipped", f"no Wikidata item with CIK {company.cik}")
    entities = []
    for qid in qids:
        entity = get_entity(client, qid)
        if entity_has_cik(entity, company.cik):
            entities.append((qid, entity))
    if len(entities) != 1:
        found = ", ".join(q for q, _ in entities) or "none confirmed"
        return Outcome(ticker, "skipped", f"ambiguous or unconfirmed CIK match ({found})")
    qid, entity = entities[0]
    label = ((entity.get("labels") or {}).get("en") or {}).get("value") or company.name

    candidates = logo_candidates(entity)
    if not candidates:
        return Outcome(ticker, "skipped", f"{qid} has no current P8972/P154 logo")
    reasons: list[str] = []
    for cand in candidates:
        if have and not force and cand.prop != P_ICON:
            reasons.append(f"{cand.prop} {cand.file_name}: not a square icon, existing wordmark kept")
            continue
        try:
            info = get_file_info(client, cand.file_name)
        except FetchError as exc:
            reasons.append(f"{cand.prop} {cand.file_name}: {exc}")
            continue
        if info.mime != "image/svg+xml":
            reasons.append(f"{cand.prop} {cand.file_name}: {info.mime or 'unknown type'}, not SVG")
            continue
        if info.size > MAX_SVG_BYTES:
            reasons.append(f"{cand.prop} {cand.file_name}: {info.size // 1024} KB > 400 KB")
            continue
        raw = client.get_bytes(info.url, kind="files", max_bytes=MAX_SVG_BYTES)
        try:
            result = sanitize_svg(raw)
        except SanitizeError as exc:
            reasons.append(f"{cand.prop} {cand.file_name}: sanitizer refused ({exc})")
            continue
        status = "found"
        if have:
            status = "swapped" if not force else "replaced"
            if status == "swapped" and result.shape != "mark":
                reasons.append(f"{cand.prop} {cand.file_name}: icon is not square, existing wordmark kept")
                continue
        row = SourceRow(ticker, str(label), qid, info.file_name, info.page_url, info.license, cand.prop)
        return Outcome(
            ticker,
            status,
            f"{qid}",
            prop=cand.prop,
            shape=result.shape,
            file_name=info.file_name,
            license=info.license,
            svg=result.svg,
            row=row,
            notes=result.notes,
        )
    if have:
        return Outcome(ticker, "kept", "; ".join(reasons) or "existing logo kept", shape=existing_shape or "")
    return Outcome(ticker, "skipped", "; ".join(reasons))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--dry-run", action="store_true", help="look up and sanitize, write nothing")
    parser.add_argument("--tickers", help="comma-separated tickers to process (default: all)")
    parser.add_argument("--force", action="store_true", help="refetch and replace existing logos")
    args = parser.parse_args(argv)

    try:
        wanted = parse_tickers_arg(args.tickers)
    except ValueError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    client = PoliteClient(use_cache=not args.force, write_cache=not args.dry_run)
    try:
        companies, source = load_companies(client)
        if wanted is not None:
            unknown = sorted(set(wanted) - {c.ticker for c in companies})
            if unknown:
                print(f"note: not in the library, ignored: {', '.join(unknown)}", file=sys.stderr)
            companies = [c for c in companies if c.ticker in wanted]
        manifest_text = MANIFEST_PATH.read_text(encoding="utf-8")
        manifest = read_manifest(manifest_text)
        sources_text = SOURCES_PATH.read_text(encoding="utf-8")
        _block(sources_text, SOURCES_BEGIN, SOURCES_END)
        print(f"{len(companies)} companies from {source}{' (dry run)' if args.dry_run else ''}", file=sys.stderr)

        outcomes: list[Outcome] = []
        for company in companies:
            try:
                outcome = process_company(client, company, manifest, force=args.force)
            except (FetchError, DisallowedURLError, ValueError) as exc:
                outcome = Outcome(company.ticker, "skipped", f"lookup failed: {exc}")
            outcomes.append(outcome)
            print(f"  {company.ticker}: {outcome.status} {outcome.detail}", file=sys.stderr)

        written = [o for o in outcomes if o.svg and o.row is not None]
        if not args.dry_run and written:
            LOGO_DIR.mkdir(parents=True, exist_ok=True)
            for o in written:
                (LOGO_DIR / f"{o.ticker}.svg").write_text(o.svg, encoding="utf-8")
            new_manifest = rewrite_manifest(manifest_text, {o.ticker: o.shape for o in written})
            if new_manifest != manifest_text:
                MANIFEST_PATH.write_text(new_manifest, encoding="utf-8")
            new_sources = rewrite_sources(sources_text, {o.ticker: o.row for o in written if o.row})
            if new_sources != sources_text:
                SOURCES_PATH.write_text(new_sources, encoding="utf-8")
    except ScriptError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    finally:
        client.close()

    print_summary(outcomes, dry_run=args.dry_run, network_calls=client.network_calls)
    return 0


def print_summary(outcomes: list[Outcome], *, dry_run: bool, network_calls: int) -> None:
    header = ("Ticker", "Result", "Prop", "Shape", "Commons file / reason", "License")
    rows = []
    for o in outcomes:
        what = o.file_name if o.svg else o.detail
        rows.append((o.ticker, o.status, o.prop, o.shape, what, o.license))
    widths = [min(max(len(str(r[i])) for r in [header, *rows]), 60) for i in range(len(header))]
    for r in [header, tuple("-" * w for w in widths), *rows]:
        print("  ".join(str(c)[: widths[i]].ljust(widths[i]) for i, c in enumerate(r)).rstrip())
    swaps = [o.ticker for o in outcomes if o.status in ("swapped", "replaced")]
    if swaps:
        print(f"\nReplaced existing logos: {', '.join(swaps)}")
    for o in outcomes:
        if o.notes:
            print(f"{o.ticker} sanitizer: {'; '.join(o.notes)}")
    print(f"\n{network_calls} network request(s){'; dry run, nothing written' if dry_run else ''}")


if __name__ == "__main__":
    sys.exit(main())
