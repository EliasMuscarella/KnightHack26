def normalize_ticker(raw: str) -> str:
    """Uppercase + trim, then validate against ^[A-Z.\\-]{1,6}$. Raises ValueError otherwise."""
    if not isinstance(raw, str):
        raise ValueError("ticker must be a string")
    upper = raw.strip().upper()
    if not TICKER_RE.fullmatch(upper):
        raise ValueError(f"invalid ticker: {raw!r}")
    return upper


def parse_tickers_arg(value: str | None) -> list[str] | None:
    if value is None:
        return None
    parts = [p for p in (s.strip() for s in value.split(",")) if p]
    if not parts:
        raise ValueError("--tickers is empty")
    return sorted({normalize_ticker(p) for p in parts})


def cik_forms(cik: str) -> list[str]:
    """The 10-digit zero-padded form first, then the unpadded form (deduplicated)."""
    digits = str(cik).strip()
    if not CIK_RE.fullmatch(digits) or int(digits) == 0:
        raise ValueError(f"invalid CIK: {cik!r}")
    padded = digits.zfill(10)
    unpadded = str(int(digits))
    return [padded] if padded == unpadded else [padded, unpadded]


