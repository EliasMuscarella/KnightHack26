@dataclass(frozen=True)
class Company:
    ticker: str
    name: str
    cik: str


def _company_from(obj: object) -> Company | None:
    if not isinstance(obj, dict):
        return None
    try:
        ticker = normalize_ticker(str(obj.get("ticker", "")))
        cik_forms(str(obj.get("cik", "")))
    except ValueError:
        return None
    name = obj.get("name")
    return Company(ticker=ticker, name=str(name) if isinstance(name, str) else ticker, cik=str(obj["cik"]).strip())


def load_companies(client: PoliteClient, published_dir: Path = PUBLISHED_DIR) -> tuple[list[Company], str]:
    """Companies from the local API, else from published reports. Returns (companies, source)."""
    try:
        payload = client.get_live_json(COMPANIES_URL)
        rows = payload.get("companies") if isinstance(payload, dict) else None
        if isinstance(rows, list):
            found = {c.ticker: c for c in (_company_from(r) for r in rows) if c is not None}
            if found:
                return [found[t] for t in sorted(found)], "api"
    except (FetchError, DisallowedURLError, httpx.HTTPError):
        pass
    found: dict[str, Company] = {}
    for path in sorted(published_dir.glob("*.json")):
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        company = _company_from(data.get("company") if isinstance(data, dict) else None)
        if company is not None and not (isinstance(data, dict) and data.get("is_fixture")):
            found.setdefault(company.ticker, company)
    if not found:
        raise ScriptError("no companies: the API at localhost:8000 is down and data/published/ has none")
    return [found[t] for t in sorted(found)], "published"


