def find_qids(client: PoliteClient, cik: str) -> list[str]:
    qids: list[str] = []
    for form in cik_forms(cik):
        payload = client.get_api(
            WIKIDATA_API,
            {
                "action": "query",
                "list": "search",
                "srsearch": f"haswbstatement:{P_CIK}={form}",
                "srnamespace": "0",
                "srlimit": "10",
            },
        )
        for hit in (payload.get("query") or {}).get("search") or []:
            title = hit.get("title") if isinstance(hit, dict) else None
            if isinstance(title, str) and QID_RE.fullmatch(title) and title not in qids:
                qids.append(title)
    return qids


def get_entity(client: PoliteClient, qid: str) -> dict:
    if not QID_RE.fullmatch(qid):
        raise FetchError(f"bad QID {qid!r}")
    payload = client.get_api(
        WIKIDATA_API,
        {"action": "wbgetentities", "ids": qid, "props": "claims|labels", "languages": "en"},
    )
    entity = (payload.get("entities") or {}).get(qid)
    if not isinstance(entity, dict) or "missing" in entity:
        raise FetchError(f"{qid} not found")
    return entity


def entity_has_cik(entity: dict, cik: str) -> bool:
    forms = set(cik_forms(cik))
    for claim in (entity.get("claims") or {}).get(P_CIK, []):
        value = ((claim.get("mainsnak") or {}).get("datavalue") or {}).get("value")
        if claim.get("rank") != "deprecated" and isinstance(value, str) and value.strip() in forms:
            return True
    return False


def _qualifier_time(claim: dict, prop: str) -> str:
    for q in (claim.get("qualifiers") or {}).get(prop, []):
        value = (q.get("datavalue") or {}).get("value")
        if isinstance(value, dict) and isinstance(value.get("time"), str):
            return value["time"]
        if q.get("snaktype") in ("somevalue", "novalue") and prop == P_END:
            return "unknown"
    return ""


def logo_candidates(entity: dict) -> list[LogoCandidate]:
    """Current logo files in preference order: P8972 before P154; within a property, values
    without an end date only (an end date marks a former logo), preferred rank first, then the
    latest start date, then the item's own order. Deprecated values are never used."""
    out: list[LogoCandidate] = []
    claims = entity.get("claims") or {}
    for prop in (P_ICON, P_LOGO):
        found: list[tuple[tuple, LogoCandidate]] = []
        for index, claim in enumerate(claims.get(prop, [])):
            snak = claim.get("mainsnak") or {}
            value = (snak.get("datavalue") or {}).get("value")
            rank = claim.get("rank", "normal")
            if snak.get("snaktype") != "value" or not isinstance(value, str) or rank == "deprecated":
                continue
            cand = LogoCandidate(
                prop=prop,
                file_name=value.strip(),
                rank=rank,
                has_end=bool(_qualifier_time(claim, P_END)),
                start=_qualifier_time(claim, P_START),
            )
            if cand.has_end:
                continue
            # Sort: preferred first, then the latest start (empty start sorts last), then order.
            key = (rank != "preferred", _neg_time(cand.start), index)
            found.append((key, cand))
        out.extend(c for _, c in sorted(found, key=lambda kc: kc[0]))
    return out


def _neg_time(value: str) -> tuple[int, str]:
    # Later dates first; ISO-like "+2012-08-24T..." strings compare lexically within a sign.
    if not value:
        return (1, "")
    inverted = "".join(chr(0x10FFFF - ord(ch)) if ch.isdigit() else ch for ch in value)
    return (0, inverted)


_TAG_RE = re.compile(r"<[^>]*>")


def _plain(value: object, limit: int = 120) -> str:
    if not isinstance(value, str):
        return ""
    text = html.unescape(_TAG_RE.sub(" ", value))
    text = re.sub(r"\s+", " ", text).strip().replace("|", "/").replace("<", "").replace(">", "")
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "…"


def get_file_info(client: PoliteClient, file_name: str) -> FileInfo:
    title = f"File:{file_name}"
    payload = client.get_api(
        COMMONS_API,
        {
            "action": "query",
            "titles": title,
            "prop": "imageinfo",
            "iiprop": "url|size|mime|extmetadata",
            "iiextmetadatafilter": "LicenseShortName|Credit|Artist",
        },
    )
    pages = (payload.get("query") or {}).get("pages") or []
    page = pages[0] if isinstance(pages, list) and pages else {}
    infos = page.get("imageinfo") if isinstance(page, dict) else None
    if not infos or not isinstance(infos[0], dict):
        raise FetchError(f"no imageinfo for {title}")
    info = infos[0]
    meta = info.get("extmetadata") or {}

    def meta_value(key: str) -> str:
        entry = meta.get(key)
        return _plain(entry.get("value")) if isinstance(entry, dict) else ""

    license_text = meta_value("LicenseShortName") or "unknown"
    extras = []
    for key in ("Artist", "Credit"):
        value = meta_value(key)
        # Commons metadata is user-edited; raw wiki template markup ("{{...}}") is not attribution
        # text (Alphabet's file once carried vandalism there), so it is left out, never published.
        if value and "{{" not in value and "}}" not in value:
            extras.append(f"{key}: {value}")
    if extras:
        license_text = f"{license_text} ({'; '.join(extras)})"

    raw_url = str(info.get("url", ""))
    parts = urlsplit(raw_url)
    url = urlunsplit(("https", parts.netloc, parts.path, "", ""))  # drop utm_* query string
    check_url(url)
    if parts.netloc.lower() != "upload.wikimedia.org":
        raise FetchError("file is not hosted on upload.wikimedia.org")
    page_url = f"https://commons.wikimedia.org/wiki/{quote(title.replace(' ', '_'), safe=':/()_,.-')}"
    return FileInfo(
        file_name=file_name,
        url=url,
        page_url=page_url,
        mime=str(info.get("mime", "")),
        size=int(info.get("size") or 0),
        license=license_text,
    )


