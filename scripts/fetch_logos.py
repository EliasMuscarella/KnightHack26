@dataclass
class SanitizeResult:
    svg: str
    width: float
    height: float
    notes: list[str] = field(default_factory=list)

    @property
    def shape(self) -> str:
        return classify_shape(self.width, self.height)


def classify_shape(width: float, height: float) -> str:
    """"mark" when the viewBox is at most 1.6 times wider than tall, else "wordmark"."""
    if width <= 0 or height <= 0:
        raise ValueError("viewBox must have a positive size")
    return "mark" if width / height <= MARK_MAX_RATIO else "wordmark"


def _split(tag: str) -> tuple[str | None, str]:
    if tag.startswith("{"):
        ns, _, local = tag[1:].partition("}")
        return ns, local
    return None, tag


def _safe_value(value: str) -> bool:
    """A value is safe when it uses no external url(), no script scheme, no CSS escapes or
    at-rules, and only ordinary characters."""
    if not SAFE_VALUE_RE.fullmatch(value):
        return False
    lowered = value.lower()
    if any(bad in lowered for bad in ("javascript", "expression", "data:", "@", "\\")):
        return False
    for match in URL_FUNC_RE.finditer(value):
        if not INTERNAL_HREF_RE.fullmatch(match.group(2).strip()):
            return False
    if "url(" in lowered.replace(" ", "") and not URL_FUNC_RE.search(value):
        return False
    return True


def _parse_declarations(text: str) -> list[tuple[str, str]] | None:
    """Parse `prop: value; ...`. Returns None when the text is not plain declarations."""
    out: list[tuple[str, str]] = []
    for chunk in text.split(";"):
        if not chunk.strip():
            continue
        prop, sep, value = chunk.partition(":")
        if not sep:
            return None
        out.append((prop.strip().lower(), value.replace("!important", "").strip()))
    return out


def _clean_style(text: str, notes: list[str]) -> str:
    kept: list[str] = []
    decls = _parse_declarations(text)
    if decls is None:
        notes.append("dropped unparseable style attribute")
        return ""
    for prop, value in decls:
        if prop in SAFE_CSS_PROPS and value and _safe_value(value):
            kept.append(f"{prop}:{value}")
        elif prop not in SAFE_CSS_PROPS and not prop.startswith("-"):
            notes.append(f"dropped style property {prop}")
    return ";".join(kept)


_CSS_COMMENT_RE = re.compile(r"/\*.*?\*/", re.DOTALL)
_CSS_RULE_RE = re.compile(r"([^{}]+)\{([^{}]*)\}")
_SIMPLE_SELECTOR_RE = re.compile(r"^(?:([A-Za-z][\w\-]*)|\.([A-Za-z_][\w\-]*)|#([A-Za-z_][\w\-]*))$")


@dataclass
class _CssRule:
    kind: str  # "tag" | "class" | "id"
    name: str
    specificity: int
    order: int
    declarations: list[tuple[str, str]]


def _parse_stylesheet(text: str) -> list[_CssRule]:
    """Simple stylesheets only (`.cls`, `tag`, `#id` selectors, comma lists). Anything else
    (at-rules, combinators, pseudo-classes, external urls) raises SanitizeError."""
    css = _CSS_COMMENT_RE.sub(" ", text)
    if "@" in css or "\\" in css or "<" in css:
        raise SanitizeError("stylesheet with at-rules or escapes")
    rules: list[_CssRule] = []
    consumed = _CSS_RULE_RE.sub("", css)
    if consumed.strip():
        raise SanitizeError("stylesheet that is not plain rules")
    for order, match in enumerate(_CSS_RULE_RE.finditer(css)):
        decls = _parse_declarations(match.group(2))
        if decls is None:
            raise SanitizeError("stylesheet rule that is not plain declarations")
        for selector in match.group(1).split(","):
            sel = _SIMPLE_SELECTOR_RE.fullmatch(selector.strip())
            if not sel:
                raise SanitizeError(f"unsupported CSS selector {selector.strip()!r}")
            tag, cls, ident = sel.groups()
            if tag:
                rules.append(_CssRule("tag", tag, 1, order, decls))
            elif cls:
                rules.append(_CssRule("class", cls, 10, order, decls))
            else:
                rules.append(_CssRule("id", ident, 100, order, decls))
    return rules


def _css_for(elem: ET.Element, local: str, rules: list[_CssRule]) -> list[tuple[str, str]]:
    classes = set((elem.get("class") or "").split())
    ident = elem.get("id")
    matched = [
        r
        for r in rules
        if (r.kind == "tag" and r.name == local)
        or (r.kind == "class" and r.name in classes)
        or (r.kind == "id" and r.name == ident)
    ]
    matched.sort(key=lambda r: (r.specificity, r.order))
    decls: list[tuple[str, str]] = []
    for rule in matched:
        decls.extend(rule.declarations)
    return decls


def _length_px(value: str | None) -> float | None:
    if value is None:
        return None
    match = LENGTH_RE.fullmatch(value)
    if not match:
        return None
    return float(match.group(1)) * UNIT_PX[match.group(2)]


def _fmt(num: float) -> str:
    text = f"{num:.4f}".rstrip("0").rstrip(".")
    return text or "0"


def _parse_viewbox(value: str) -> tuple[float, float, float, float] | None:
    parts = re.split(r"[\s,]+", value.strip())
    if len(parts) != 4:
        return None
    try:
        nums = tuple(float(p) for p in parts)
    except ValueError:
        return None
    if nums[2] <= 0 or nums[3] <= 0:
        return None
    return nums  # type: ignore[return-value]


def sanitize_svg(raw: bytes) -> SanitizeResult:
    """Rebuild an SVG from an element/attribute allowlist. Raises SanitizeError (fail closed)."""
    if len(raw) > MAX_SVG_BYTES:
        raise SanitizeError(f"file larger than {MAX_SVG_BYTES // 1024} KB")
    lowered = raw.lower()
    if b"<!doctype" in lowered or b"<!entity" in lowered:
        raise SanitizeError("DOCTYPE or ENTITY declaration")
    try:
        root = ET.fromstring(raw)  # comments and processing instructions are discarded
    except ET.ParseError as exc:
        raise SanitizeError(f"not well-formed XML: {exc}") from exc
    ns, local = _split(root.tag)
    if local != "svg" or ns not in (SVG_NS, None):
        raise SanitizeError("root element is not <svg>")

    notes: list[str] = []
    rules: list[_CssRule] = []
    for elem in root.iter():
        e_ns, e_local = _split(elem.tag) if isinstance(elem.tag, str) else (None, "")
        if e_local == "style" and e_ns in (SVG_NS, None):
            rules.extend(_parse_stylesheet("".join(elem.itertext())))
    if rules:
        notes.append(f"inlined {len(rules)} CSS rule(s) from <style>")

    out: list[str] = []
    viewbox = _root_viewbox(root)
    _emit(root, out, rules, notes, is_root=True, viewbox=viewbox)
    svg = "".join(out) + "\n"
    _verify(svg)
    return SanitizeResult(svg=svg, width=viewbox[2], height=viewbox[3], notes=sorted(set(notes)))


def _root_viewbox(root: ET.Element) -> tuple[float, float, float, float]:
    value = root.get("viewBox")
    if value is not None:
        parsed = _parse_viewbox(value)
        if parsed is None:
            raise SanitizeError(f"invalid viewBox {value!r}")
        return parsed
    width, height = _length_px(root.get("width")), _length_px(root.get("height"))
    if not width or not height:
        raise SanitizeError("no viewBox and no absolute width/height to derive one")
    return (0.0, 0.0, width, height)


def _clean_attr(name: str, value: str, local: str, notes: list[str]) -> str | None:
    value = value.strip()
    if name.lower().startswith("on"):
        notes.append(f"dropped event handler {name}")
        return None
    if name == "href":
        if local in ("use", "linearGradient", "radialGradient") and INTERNAL_HREF_RE.fullmatch(value):
            return value
        notes.append(f"dropped href on <{local}>")
        return None
    if name == "id":
        return value if ID_RE.fullmatch(value) else None
    if name == "style":
        return None  # merged separately
    if name not in ALLOWED_ATTRS:
        return None
    if not _safe_value(value):
        notes.append(f"dropped unsafe {name} value")
        return None
    if name not in PAINT_ATTRS and "url(" in value.lower():
        notes.append(f"dropped url() in {name}")
        return None
    return value


def _emit(
    elem: ET.Element,
    out: list[str],
    rules: list[_CssRule],
    notes: list[str],
    *,
    is_root: bool = False,
    viewbox: tuple[float, float, float, float] | None = None,
    in_text: bool = False,
) -> None:
    ns, local = _split(elem.tag)
    attrs: dict[str, str] = {}
    for raw_name, raw_value in elem.attrib.items():
        a_ns, a_local = _split(raw_name)
        if a_ns == XLINK_NS and a_local == "href":
            name = "href"
        elif a_ns == XML_NS and a_local == "space" and local in TEXT_ELEMENTS:
            attrs["xml:space"] = "preserve" if raw_value.strip() == "preserve" else "default"
            continue
        elif a_ns is not None:
            continue  # editor namespaces (inkscape:, sodipodi:, xml:, i:, ...)
        else:
            name = a_local
        cleaned = _clean_attr(name, raw_value, local, notes)
        if cleaned is not None:
            attrs[name] = cleaned

    style_decls = _css_for(elem, local, rules) + (_parse_declarations(elem.get("style") or "") or [])
    style = _clean_style(";".join(f"{p}:{v}" for p, v in style_decls), notes) if style_decls else ""
    if style:
        attrs["style"] = style

    if local == "use" and "href" not in attrs:
        notes.append("dropped <use> without an internal href")
        return

    if is_root:
        assert viewbox is not None
        for key in ("width", "height", "x", "y"):
            attrs.pop(key, None)
        attrs["viewBox"] = " ".join(_fmt(n) for n in viewbox)
        ordered = [("xmlns", SVG_NS), ("viewBox", attrs.pop("viewBox"))] + sorted(attrs.items())
    else:
        ordered = sorted(attrs.items())

    out.append(f"<{local}")
    for key, value in ordered:
        out.append(f' {key}="{_escape_attr(value)}"')

    children: list[str] = []
    text_inside = in_text or local in TEXT_ELEMENTS
    if text_inside and elem.text:
        children.append(_escape_text(elem.text))
    for child in elem:
        if not isinstance(child.tag, str):
            continue
        c_ns, c_local = _split(child.tag)
        if c_ns not in (SVG_NS, None):
            pass  # editor element (sodipodi:namedview, RDF metadata, ...): dropped
        elif c_local in ALLOWED_ELEMENTS:
            if text_inside and c_local != "tspan":
                raise SanitizeError(f"<{c_local}> inside text")
            _emit(child, children, rules, notes, in_text=text_inside)
        elif c_local == "switch":
            _emit_switch(child, children, rules, notes)
        elif c_local in DROPPED_ELEMENTS:
            if c_local not in ("title", "desc", "metadata", "style"):
                notes.append(f"dropped <{c_local}>")
        else:
            raise SanitizeError(f"unsupported element <{c_local}>")
        if text_inside and child.tail:
            children.append(_escape_text(child.tail))
    if children:
        out.append(">")
        out.extend(children)
        out.append(f"</{local}>")
    else:
        out.append("/>")


def _emit_switch(elem: ET.Element, out: list[str], rules: list[_CssRule], notes: list[str]) -> None:
    """<switch> renders its first matching child. Kept as <g> only when exactly one renderable
    child remains after foreignObject and friends are removed; otherwise fail closed."""
    kept = []
    for child in elem:
        if not isinstance(child.tag, str):
            continue
        c_ns, c_local = _split(child.tag)
        if c_ns not in (SVG_NS, None) or c_local in DROPPED_ELEMENTS:
            continue
        kept.append(child)
    if len(kept) != 1:
        raise SanitizeError("<switch> with several alternatives")
    notes.append("unwrapped <switch>")
    wrapper = ET.Element(f"{{{SVG_NS}}}g", {k: v for k, v in elem.attrib.items()})
    wrapper.append(kept[0])
    _emit(wrapper, out, rules, notes)


def _escape_attr(value: str) -> str:
    return (
        value.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")
    )


def _escape_text(value: str) -> str:
    return value.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def _verify(svg: str) -> None:
    """Re-parse the output and confirm only allowlisted names remain (fail closed)."""
    for pattern in FORBIDDEN_OUTPUT_RES:
        if pattern.search(svg):
            raise SanitizeError(f"output still matches {pattern.pattern!r}")
    try:
        root = ET.fromstring(svg.encode("utf-8"))
    except ET.ParseError as exc:  # pragma: no cover - our own serializer
        raise SanitizeError("output is not well-formed") from exc
    for elem in root.iter():
        ns, local = _split(elem.tag)
        if ns != SVG_NS or local not in ALLOWED_ELEMENTS:
            raise SanitizeError(f"output has <{local}>")
        for name, value in elem.attrib.items():
            if name == f"{{{XML_NS}}}space" and local in TEXT_ELEMENTS:
                continue
            if name not in ALLOWED_ATTRS:
                raise SanitizeError(f"output has attribute {name}")
            if name == "href" and not INTERNAL_HREF_RE.fullmatch(value):
                raise SanitizeError("output has an external href")


