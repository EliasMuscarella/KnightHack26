_MANIFEST_LINE_RE = re.compile(r'^\s*"?([A-Z.\-]{1,6})"?\s*:\s*"(mark|wordmark)",?\s*$')


def _block(text: str, begin: str, end: str) -> tuple[int, int]:
    start = text.find(begin)
    stop = text.find(end, start + len(begin)) if start >= 0 else -1
    if start < 0 or stop < 0 or text.count(begin) != 1 or text.count(end) != 1:
        raise ScriptError(f"generated-block markers not found exactly once: {begin!r} / {end!r}")
    return start, stop


def read_manifest(text: str) -> dict[str, str]:
    start, stop = _block(text, MANIFEST_BEGIN, MANIFEST_END)
    entries: dict[str, str] = {}
    for line in text[start + len(MANIFEST_BEGIN) : stop].splitlines():
        if not line.strip():
            continue
        match = _MANIFEST_LINE_RE.fullmatch(line)
        if not match:
            raise ScriptError(f"unexpected line in the generated manifest block: {line.strip()!r}")
        entries[match.group(1)] = match.group(2)
    return entries


def rewrite_manifest(text: str, updates: dict[str, str]) -> str:
    """Merge `updates` into the generated block; entries sorted by ticker, one per line."""
    entries = read_manifest(text)
    for ticker, shape in updates.items():
        if shape not in ("mark", "wordmark"):
            raise ValueError(f"invalid shape {shape!r}")
        entries[normalize_ticker(ticker)] = shape
    start, stop = _block(text, MANIFEST_BEGIN, MANIFEST_END)
    line_start = text.rfind("\n", 0, start) + 1
    indent = text[line_start:start]
    body = "".join(
        f"{indent}{t if re.fullmatch(r'[A-Z]+', t) else json.dumps(t)}: \"{entries[t]}\",\n"
        for t in sorted(entries)
    )
    return text[: start + len(MANIFEST_BEGIN)] + "\n" + body + indent + text[stop:]


@dataclass
class SourceRow:
    ticker: str
    company: str
    qid: str
    file_name: str
    page_url: str
    license: str
    prop: str

    def render(self) -> str:
        cells = [
            self.ticker,
            _md_cell(self.company),
            f"[{self.qid}](https://www.wikidata.org/wiki/{self.qid})",
            f"[{_md_cell(self.file_name)}]({self.page_url})",
            _md_cell(self.license),
            self.prop,
        ]
        return "| " + " | ".join(cells) + " |"


def _md_cell(value: str) -> str:
    return re.sub(r"\s+", " ", value.replace("|", "/").replace("[", "(").replace("]", ")")).strip()


def rewrite_sources(text: str, rows: dict[str, SourceRow]) -> str:
    """Replace/add one row per ticker in the generated table; other rows are kept verbatim."""
    start, stop = _block(text, SOURCES_BEGIN, SOURCES_END)
    existing: dict[str, str] = {}
    for line in text[start + len(SOURCES_BEGIN) : stop].splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if line.startswith("|") and cells and TICKER_RE.fullmatch(cells[0]) and re.search("[A-Z]", cells[0]):
            existing[cells[0]] = line.rstrip()
    for ticker, row in rows.items():
        existing[ticker] = row.render()
    body = SOURCES_HEADER + "\n" + "".join(existing[t] + "\n" for t in sorted(existing))
    return text[: start + len(SOURCES_BEGIN)] + "\n" + body + text[stop:]


