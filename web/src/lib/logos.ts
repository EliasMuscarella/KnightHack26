/**
 * Bundled company logos (web/public/logos/{TICKER}.svg, or .png for the hand-added raster logos
 * listed in RASTER_LOGOS; sources in web/public/logos/SOURCES.md).
 * Only tickers listed here get an image request, so a missing logo never causes a 404; every other
 * ticker renders the monogram badge. Logos are served from /logos/ only, never from an external URL.
 */
import { TICKER_PATTERN } from "@/lib/ticker";

/** "mark": roughly square symbol. "wordmark": a wide logotype (viewBox, or PNG size, wider than 1.6:1), padded differently in the same tile. */
export type LogoShape = "mark" | "wordmark";

const LOGO_MANIFEST = {
  // BEGIN GENERATED by scripts/fetch_logos.py
  AAPL: "mark",
  ADBE: "wordmark",
  AMD: "wordmark",
  AMZN: "mark",
  BY: "mark",
  CRWD: "wordmark",
  GOOGL: "wordmark",
  JNJ: "wordmark",
  LLY: "wordmark",
  LMT: "wordmark",
  MA: "wordmark",
  META: "mark",
  MSFT: "mark",
  NVDA: "wordmark",
  SF: "wordmark",
  STT: "wordmark",
  TSLA: "mark",
  TTWO: "mark",
  V: "wordmark",
  WMT: "mark",
  // END GENERATED
} as const satisfies Record<string, LogoShape>;

export type LogoTicker = keyof typeof LOGO_MANIFEST;

/**
 * Hand-added logos that exist only as a raster image (no genuine SVG on Wikimedia Commons), served as
 * /logos/{TICKER}.png. Kept outside the generated block; sources in SOURCES.md.
 */
// RASTER LOGOS
const RASTER_LOGOS: ReadonlySet<string> = new Set(["ADBE", "BY", "LMT"]);

export interface BundledLogo {
  src: string;
  shape: LogoShape;
}

function hasLogo(ticker: string): ticker is LogoTicker {
  return Object.prototype.hasOwnProperty.call(LOGO_MANIFEST, ticker);
}

/** The bundled logo for a ticker, or null. The ticker is validated before any path is built. */
export function logoFor(ticker: string): BundledLogo | null {
  const upper = typeof ticker === "string" ? ticker.trim().toUpperCase() : "";
  if (!TICKER_PATTERN.test(upper) || !hasLogo(upper)) return null;
  return { src: `/logos/${upper}.${RASTER_LOGOS.has(upper) ? "png" : "svg"}`, shape: LOGO_MANIFEST[upper] };
}
