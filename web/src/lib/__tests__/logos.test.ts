import assert from "node:assert/strict";
import { readdirSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";

// logos.ts imports through the "@/" alias, which Node's runner cannot resolve, so the manifest is
// read from the generated block in the source (the block scripts/fetch_logos.py rewrites).
const here = dirname(fileURLToPath(import.meta.url));
const manifestSource = readFileSync(join(here, "..", "logos.ts"), "utf8");
const logoDir = join(here, "..", "..", "..", "public", "logos");

function manifest(): Map<string, string> {
  const match = /\/\/ BEGIN GENERATED by scripts\/fetch_logos\.py\n([\s\S]*?)\n\s*\/\/ END GENERATED/.exec(manifestSource);
  assert.ok(match, "generated manifest block not found in logos.ts");
  const entries = new Map<string, string>();
  for (const line of match[1].split("\n")) {
    const entry = /^\s*"?([A-Z.\-]{1,6})"?:\s*"(mark|wordmark)",\s*$/.exec(line);
    assert.ok(entry, `unexpected manifest line: ${line}`);
    entries.set(entry[1], entry[2]);
  }
  return entries;
}

/** Tickers in the hand-maintained RASTER_LOGOS set (served as .png instead of .svg). */
function rasterTickers(): Set<string> {
  const match = /RASTER_LOGOS[^=]*=\s*new Set\(\[([^\]]*)\]\)/.exec(manifestSource);
  assert.ok(match, "RASTER_LOGOS set not found in logos.ts");
  return new Set([...match[1].matchAll(/"([A-Z.\-]{1,6})"/g)].map((m) => m[1]));
}

const files = readdirSync(logoDir);
const byExt = (ext: string) =>
  files
    .filter((f) => f.endsWith(ext))
    .map((f) => f.slice(0, -ext.length))
    .sort();
const svgs = byExt(".svg");
const pngs = byExt(".png");

test("every manifest ticker has a bundled file in its format", () => {
  const raster = rasterTickers();
  const missing = [...manifest().keys()].filter((t) => !(raster.has(t) ? pngs : svgs).includes(t));
  assert.deepEqual(missing, []);
});

test("every bundled file is in the manifest, and PNGs only for listed raster logos", () => {
  const listed = manifest();
  const raster = rasterTickers();
  assert.deepEqual(svgs.filter((t) => !listed.has(t)), []);
  assert.deepEqual(pngs.filter((t) => !listed.has(t) || !raster.has(t)), []);
  for (const t of raster) assert.ok(!svgs.includes(t), `${t} has both a PNG and an SVG`);
});

test("bundled PNGs are real PNG files", () => {
  for (const t of pngs) {
    const head = readFileSync(join(logoDir, `${t}.png`)).subarray(0, 8);
    assert.deepEqual([...head], [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a], `${t}.png is not a PNG`);
  }
});

test("the manifest is sorted and every ticker is valid", () => {
  const tickers = [...manifest().keys()];
  assert.ok(tickers.length > 0);
  assert.deepEqual(tickers, [...tickers].sort());
  for (const t of tickers) assert.match(t, /^[A-Z.\-]{1,6}$/);
});

test("bundled SVGs carry no active or external content", () => {
  for (const t of svgs) {
    const text = readFileSync(join(logoDir, `${t}.svg`), "utf8");
    for (const bad of [/<script/i, /\son[a-z]+\s*=/i, /href="(?!#)/i, /javascript:/i, /foreignObject/i, /<image/i, /<!DOCTYPE|<!ENTITY/i]) {
      assert.doesNotMatch(text, bad, `${t}.svg matches ${bad}`);
    }
  }
});
